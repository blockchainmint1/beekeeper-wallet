#!/usr/bin/env bash
# Build a clean public copy of BeeKeeper Wallet: tracked files only, no git
# history, and none of the private material (audit reports, open-item lists,
# partner handoffs, Lovable plans, local env). Usage:
#   scripts/make-public-copy.sh /tmp/beekeeper-wallet-public
set -euo pipefail
OUT="${1:?usage: make-public-copy.sh <empty output folder>}"
ROOT="$(git rev-parse --show-toplevel)"
if [ -e "$OUT" ] && [ -n "$(ls -A "$OUT" 2>/dev/null)" ]; then
  echo "Output folder must be empty: $OUT" >&2; exit 1
fi
mkdir -p "$OUT"

# Private paths (regex on repo-relative paths). docs/images stays.
PRIVATE='^(\.env$|\.lovable/|\.git/|roadmap\.md$|AGENTS\.md$|SECURITY-AUDIT\.md$|docs/(?!images/)|.*security-audit.*|.*audit-round.*)'

cd "$ROOT"
git ls-files -z | tr '\0' '\n' | grep -Pv "$PRIVATE" | while IFS= read -r f; do
  [ -f "$f" ] || continue
  mkdir -p "$OUT/$(dirname "$f")"
  cp -p "$f" "$OUT/$f"
done

# The Lovable sync notice applies to the private repo only.
python3 - "$OUT/README.md" <<'PY'
import re, sys
p = sys.argv[1]; s = open(p).read()
s = re.sub(r"> \[!IMPORTANT\]\n> This project is connected to \[Lovable\].*?keep the branch in a working state\.\n\n", "", s, flags=re.S)
open(p, "w").write(s)
PY

cat > "$OUT/.env.example" <<'ENV'
# Public values generated by Lovable Cloud (they ship in every visitor's browser).
VITE_SUPABASE_URL=
VITE_SUPABASE_PUBLISHABLE_KEY=
VITE_SUPABASE_PROJECT_ID=
ENV

# Refuse to finish if anything private slipped through.
leaks="$(cd "$OUT" && find . -type f | sed 's#^\./##' | grep -P "$PRIVATE" || true)"
if [ -n "$leaks" ]; then echo "Private files found in the copy:" >&2; echo "$leaks" >&2; exit 1; fi
echo "Public copy ready: $OUT ($(find "$OUT" -type f | wc -l) files)"
